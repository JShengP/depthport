  const storageKey = 'depthport.language';
  function normalize(value) {
    if (typeof value !== 'string') return null;
    if (value === 'en' || /^en-/i.test(value)) return 'en';
    if (/^zh(?:-|$)/i.test(value)) return 'zh-TW';
    return null;
  }
  function initialLanguage() {
    try {
      const explicit = normalize(new URLSearchParams(root.location.search).get('lang'));
      if (explicit) return explicit;
      const saved = normalize(root.localStorage.getItem(storageKey));
      if (saved) return saved;
    } catch (_) { /* Storage is optional in private/file/embedded contexts. */ }
    return normalize(root.navigator && root.navigator.language) || 'en';
  }
  let language = initialLanguage();
  function t(key, params = {}) {
    const value = messages[language][key] || messages.en[key];
    if (value === undefined) return key;
    return value.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) =>
      Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match);
  }
  function apply() {
    if (!root.document) return;
    root.document.documentElement.lang = language === 'zh-TW' ? 'zh-Hant' : 'en';
    root.document.title = t('title');
    root.document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    ['title', 'aria-label', 'placeholder', 'alt'].forEach(attr => {
      root.document.querySelectorAll('[data-i18n-' + attr + ']').forEach(el => {
        el.setAttribute(attr, t(el.getAttribute('data-i18n-' + attr)));
      });
    });
    const selector = root.document.getElementById('languageSelect');
    if (selector) selector.value = language;
  }
  function setLanguage(value, persist = true) {
    language = normalize(value) || 'en';
    if (persist) {
      try { root.localStorage.setItem(storageKey, language); } catch (_) {}
      // An explicit query must follow later UI selections on reload too.
      try {
        const url = new URL(root.location.href);
        if (url.searchParams.has('lang')) { url.searchParams.set('lang', language); root.history.replaceState(null, '', url); }
      } catch (_) {}
    }
    apply();
    if (root.dispatchEvent && root.CustomEvent) root.dispatchEvent(new CustomEvent('depthport:language'));
  }
  const api = { t, apply, setLanguage, normalize, messages, get language() { return language; } };
  root.DepthPortI18n = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
